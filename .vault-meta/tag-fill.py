ALLOWED = {tag for tag, _ in TAG_KW}

def build_kw_map():
    m = []
    seen = set()
    for tag, kws in TAG_KW:
        for kw in kws:
            if not kw or kw in seen:
                continue
            seen.add(kw)
            generic = kw in GENERIC or len(kw) <= 1
            m.append((kw, tag, generic))
    for kw, tag in EXTRA_KW:
        if kw in seen:
            continue
        seen.add(kw)
        generic = kw in GENERIC or len(kw) <= 1
        m.append((kw, tag, generic))
    return m

KW_MAP = build_kw_map()

def parse_frontmatter(text):
    m = FRONTMATTER_RE.match(text)
    if not m:
        return {}, m
    fm = {}
    current_key, current_list = None, None
    for line in m.group(1).splitlines():
        if re.match(r"^\s+-\s+", line) and current_key is not None:
            val = re.split(r"^\s+-\s+", line)[1].strip().strip('"').strip("'")
            if val:
                if current_list is None:
                    current_list = []
                current_list.append(val)
            continue
        if ":" in line and not line[:1] in (" ", "\t", "#"):
            if current_key is not None and current_list is not None:
                fm[current_key] = current_list
            k, _, v = line.partition(":")
            k, v = k.strip(), v.strip()
            if v == "":
                current_key, current_list = k, None
            else:
                if v.startswith("[") and v.endswith("]"):
                    fm[k] = [x.strip().strip('"').strip("'") for x in v[1:-1].split(",") if x.strip()]
                else:
                    fm[k] = v.strip('"').strip("'")
                current_key, current_list = k, None
    if current_key is not None and current_list is not None:
        fm[current_key] = current_list
    return fm, m

def _yq(s):
    """YAML 双引号标量:转义反斜杠与双引号。"""
    return s.replace("\\", "\\\\").replace('"', '\\"')

def _yitem(item):
    """列表项引号包裹:含双引号不含单引号→单引号包裹;否则双引号包裹。"""
    if '"' in item and "'" not in item:
        return f"'{item}'"
    return f'"{_yq(item)}"'

def dump_fm(fm):
    lines = ["---"]
    for k, v in fm.items():
        if isinstance(v, list):
            lines.append(f"{k}:" if v else f"{k}: []")
            for item in v:
                lines.append(f"  - {_yitem(item)}")
        elif isinstance(v, str) and '"' in v and "'" not in v:
            lines.append(f"{k}: '{v}'")
        else:
            lines.append(f'{k}: "{_yq(v)}"')
    lines.append("---")
    return "\n".join(lines)

def infer_tags(title, body, links):
    scores = Counter()
    title_tags = set()
    title_l, body_l = title.lower(), body.lower()
    for kw, tag, generic in KW_MAP:
        kwl = kw.lower()
        if generic:
            if title_l and kwl in title_l:
                scores[tag] += 3.0
                title_tags.add(tag)
            continue
        if title_l and kwl in title_l:
            scores[tag] += 3.0
            title_tags.add(tag)
        elif body_l and kwl in body_l:
            scores[tag] += 1.0
    # wikilink 目标名:作为弱信号
    for l in links:
        ll = l.lower()
        for kw, tag, generic in KW_MAP:
            if generic:
                continue
            if kw.lower() in ll:
                scores[tag] += 0.6
                break
    result = []
    for tag, s in scores.most_common():
        if tag not in ALLOWED:
            continue
        # 标题命中即入选;正文-only 需 ≥4 个不同关键词(防误报)
        if tag in title_tags or s >= 4.0:
            result.append(tag)
        if len(result) >= MAX_TAGS:
            break
    return result

def main():
    dry = "--dry-run" in sys.argv
    files = sorted(str(p.relative_to(ROOT)) for p in ROOT.rglob("*.md")
                   if not any(part.startswith(".") for part in p.parts))
    changed, skipped = [], 0
    stats = Counter()
    for rel in files:
        full = ROOT / rel
        if full.name in ("_index.md", "index.md"):
            continue
        text = full.read_text(encoding="utf-8")
        fm, m = parse_frontmatter(text)
        if not m:
            continue
        cur = fm.get("tags", [])
        if isinstance(cur, str):
            cur = [] if cur.strip() in ("", "[]") else [cur.strip('"').strip("'")]
        if cur:
            continue
        body = text[m.end():]
        links = [l.strip() for l in WIKILINK_RE.findall(text)]
        title = fm.get("title", "") or (body.splitlines()[0].lstrip("# ").strip() if body else "")
        tags = infer_tags(title, body, links)
        if not tags:
            skipped += 1
            if dry:
                print(f"  [SKIP] {rel}")
            continue
        fm["tags"] = tags
        if not fm.get("updated"):
            fm["updated"] = "2026-08-10"
        new_text = dump_fm(fm) + text[m.end():]
        # 安全校验:重解析后除 tags/updated 外字段必须与原始一致
        fm2, _ = parse_frontmatter(new_text)
        ok = True
        for k, v in fm2.items():
            if k in ("tags", "updated"):
                continue
            bv = fm.get(k)
            if isinstance(bv, str):
                bv = bv.strip('"').strip("'")
            if bv != v:
                ok = False
                break
        if not ok:
            skipped += 1
            print(f"  [SKIP-ROUNDTRIP] {rel} (frontmatter 含特殊引号,保留原样)")
            continue
        changed.append((rel, tags))
        for t in tags:
            stats[t] += 1
        if dry:
            print(f"  [SET ] {rel}  ->  {tags}")
        else:
            full.write_text(new_text, encoding="utf-8")
    if dry and stats:
        print("\nTop new tags:")
        for t, n in stats.most_common(15):
            print(f"  {n:4d}  {t}")
    print(f"\n{'DRY-RUN' if dry else 'APPLIED'}: {len(changed)} files tagged, {skipped} skipped (no confident tags).")

if __name__ == "__main__":
    main()
